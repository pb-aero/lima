"""Generate simple dimensioned VRML models for the custom footprints that have no vendor model in hand.
Boxes at datasheet body size + leads/pins at the footprint's pad positions. KiCad VRML unit = 0.1 inch.
Run:  python3 -I gen_models.py   (writes *.wrl next to this file)
"""
import os
OUT = os.path.dirname(os.path.abspath(__file__))
U = 1 / 2.54          # mm -> KiCad VRML units
BODY = (0.12, 0.12, 0.13); LEAD = (0.78, 0.78, 0.80); PAD = (0.85, 0.75, 0.35); MARK = (0.9, 0.9, 0.9)

def box(x0, y0, z0, x1, y1, z1, rgb):
    # KiCad flips Y between board (down) and VRML (up); footprint coords are given in board convention
    cx, cy, cz = (x0 + x1) / 2, -(y0 + y1) / 2, (z0 + z1) / 2
    sx, sy, sz = abs(x1 - x0), abs(y1 - y0), abs(z1 - z0)
    return ("Transform { translation %.4f %.4f %.4f children [ Shape { appearance Appearance { material Material "
            "{ diffuseColor %.2f %.2f %.2f } } geometry Box { size %.4f %.4f %.4f } } ] }\n"
            % (cx * U, cy * U, cz * U, *rgb, sx * U, sy * U, sz * U))

def write(name, shapes):
    with open(os.path.join(OUT, name + ".wrl"), "w") as f:
        f.write("#VRML V2.0 utf8\n# generated by gen_models.py (LIMA) - simplified, datasheet body size\n")
        f.writelines(shapes)
    print("wrote", name, len(shapes), "shapes")

# ADAU1467 CP-88-10: 12x12x0.85, 22 leads/side 0.25 wide x 0.40 long at the edge, EP 5.3
s = [box(-6, -6, 0.05, 6, 6, 0.85, BODY), box(-5.6, -5.6, 0.849, -5.0, -5.0, 0.86, MARK)]
for i in range(22):
    t = -5.25 + 0.5 * i
    s += [box(-6.0, t - .125, 0, -5.6, t + .125, .2, LEAD), box(5.6, t - .125, 0, 6.0, t + .125, .2, LEAD),
          box(t - .125, -6.0, 0, t + .125, -5.6, .2, LEAD), box(t - .125, 5.6, 0, t + .125, 6.0, .2, LEAD)]
write("AD_LFCSP-88-1EP_12x12mm_P0.5mm_CP-88-10", s)

# IM68A130A PG-TLGA-4-2: 3.35x2.5x0.98, origin = sound port; body centre x = -0.51
s = [box(-2.185, -1.25, 0.05, 1.165, 1.25, 0.98, (0.75, 0.72, 0.65)), box(-1.9, 0.75, 0.979, -1.6, 1.05, 0.99, (0.2, 0.2, 0.2))]
write("Infineon_PG-TLGA-4-2_IM68A130A", s)

# AQW612S GU SOP8: body 4.4 (x) x 9.37 (y) x 2.1, gull-wing leads to x +/-3.4 at y = +/-3.81, +/-1.27
s = [box(-2.2, -4.685, 0.1, 2.2, 4.685, 2.1, BODY), box(-1.9, -4.3, 2.099, -1.4, -3.8, 2.11, MARK)]
for y in (-3.81, -1.27, 1.27, 3.81):
    s += [box(-3.4, y - .2, 0, -2.2, y + .2, .25, LEAD), box(2.2, y - .2, 0, 3.4, y + .2, .25, LEAD)]
write("Panasonic_GU-SOP8_AQW61xS", s)

# Triad SP-74: 0.410 x 0.310 in body (10.41 x 7.87), 0.465 in tall (11.8), 0.020 in leads at the 2x3 grid, 3.5 mm below board
s = [box(-5.205, -3.935, 0.5, 5.205, 3.935, 11.8, (0.75, 0.12, 0.10))]
for x in (-3.81, 3.81):
    for y in (-2.54, 0, 2.54):
        s.append(box(x - .25, y - .25, -3.5, x + .25, y + .25, 0.5, (0.85, 0.7, 0.2)))
write("Triad_SP-74", s)

# Bourns SM-LP-5001: 12.8 (x) x 9.0 (y) x 7.5 seated, six leads at x +/-6.0 (pad centre), y = -2.54, 0, 2.54
s = [box(-6.4, -4.5, 0.3, 6.4, 4.5, 7.5, BODY)]
for x0, x1 in ((-7.2, -6.4), (6.4, 7.2)):
    for y in (-2.54, 0, 2.54):
        s.append(box(x0, y - .3, 0, x1, y + .3, 1.2, LEAD))
write("Bourns_SM-LP-5001", s)

# Cvilux CF31 24P: body 16.2 x 5.07 x 1.95 (local y 0.35..5.42, cable enters +y), 24 tails at y~0, two tabs at (+/-7, 2.75)
s = [box(-8.1, 0.35, 0, 8.1, 5.42, 1.95, (0.85, 0.80, 0.62)), box(-7.6, 3.6, 1.95, 7.6, 5.42, 2.1, BODY)]
for i in range(24):
    x = -5.75 + 0.5 * i
    s.append(box(x - .1, -0.5, 0, x + .1, 0.6, .15, LEAD))
for x in (-7.0, 7.0):
    s.append(box(x - .9, 2.0, 0, x + .9, 3.5, .3, LEAD))
write("Cvilux_CF31241D0R0-05-NH", s)
